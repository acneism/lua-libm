package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"math"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

type tableSource struct {
	file, sourceName, name, rowType string
	fields                          []string
	rows                            int
	decimal                         bool
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	source := flag.String("source", "", "Directory containing the unmodified glibc 2.39 dbl-64 source files")
	manifest := flag.String("manifest", "docs/sources.sha256", "SHA-256 manifest for every required upstream source file")
	output := flag.String("output", "tables.go", "Generated Go lookup-table file")
	flag.Parse()
	if *source == "" {
		return fmt.Errorf("-source is required")
	}
	files, err := checkedSources(*source, *manifest)
	if err != nil {
		return err
	}
	data, err := generate(files)
	if err != nil {
		return err
	}
	return os.WriteFile(*output, data, 0644)
}

func checkedSources(directory, manifest string) (map[string]string, error) {
	data, err := os.ReadFile(manifest)
	if err != nil {
		return nil, err
	}
	files := make(map[string]string)
	for _, line := range strings.Split(strings.TrimSpace(string(data)), "\n") {
		fields := strings.Fields(line)
		if len(fields) != 2 || filepath.Base(fields[1]) != fields[1] {
			return nil, fmt.Errorf("invalid source manifest line %q", line)
		}
		expected, err := hex.DecodeString(fields[0])
		if err != nil || len(expected) != sha256.Size {
			return nil, fmt.Errorf("invalid SHA-256 for %s", fields[1])
		}
		if _, duplicate := files[fields[1]]; duplicate {
			return nil, fmt.Errorf("duplicate source %s", fields[1])
		}
		contents, err := os.ReadFile(filepath.Join(directory, fields[1]))
		if err != nil {
			return nil, err
		}
		actual := sha256.Sum256(contents)
		if !bytes.Equal(actual[:], expected) {
			return nil, fmt.Errorf("SHA-256 mismatch for %s: got %x, want %s", fields[1], actual, fields[0])
		}
		files[fields[1]] = string(contents)
	}
	return files, nil
}

func generate(files map[string]string) ([]byte, error) {
	sources := []tableSource{
		{"sincostab.c", "__sincostab", "sincosTableBits", "sincosEntryBits", []string{"sine", "sineTail", "cosine", "cosineTail"}, 110, false},
		{"utan.tbl", "xfg", "tanTableBits", "tanEntryBits", []string{"argument", "tangent", "cotangent", "tangentTail"}, 186, false},
		{"uatan.tbl", "cij", "atanTableBits", "atanEntryBits", []string{"argument", "value", "linear", "quadratic", "cubic", "quartic", "quintic"}, 241, false},
		{"asincos.tbl", "asncs", "asinTableBits", "", nil, 2568, false},
		{"root.tbl", "inroot", "rootTableBits", "", nil, 128, true},
		{"powtwo.tbl", "powtwo", "powerTableBits", "", nil, 28, true},
		{"branred.h", "toverp", "twoOverPiBits", "", nil, 75, true},
	}
	var out strings.Builder
	out.WriteString("// Copyright (C) 2001-2024 Free Software Foundation, Inc.\n// IBM Accurate Mathematical Library, written by International Business Machines Corp.\n// Translated to Go from glibc 2.39 sysdeps/ieee754/dbl-64/sincostab.c, utan.tbl, uatan.tbl, asincos.tbl, root.tbl, powtwo.tbl, branred.h.\n// Modified by acneism on 2026-10-24: see NOTICE and docs/porting.md.\n// SPDX-License-Identifier: LGPL-2.1-or-later\n// Code generated by internal/cmd/gentables; DO NOT EDIT.\n\npackage libm\n\n")
	for _, source := range sources {
		text, ok := files[source.file]
		if !ok {
			return nil, fmt.Errorf("%s is absent from the verified sources", source.file)
		}
		values, err := parseTable(text, source.sourceName, source.decimal)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", source.file, err)
		}
		columns := max(1, len(source.fields))
		if len(values) != source.rows*columns {
			return nil, fmt.Errorf("%s: got %d values, want %d", source.file, len(values), source.rows*columns)
		}
		if source.rowType != "" {
			fmt.Fprintf(&out, "type %s struct {\n%s uint64\n}\n\n", source.rowType, strings.Join(source.fields, ", "))
			fmt.Fprintf(&out, "var %s = [%d]%s{\n", source.name, source.rows, source.rowType)
		} else {
			fmt.Fprintf(&out, "var %s = [%d]uint64{\n", source.name, source.rows)
		}
		for row := 0; row < source.rows; row++ {
			if columns > 1 {
				out.WriteString("{")
			}
			for column := 0; column < columns; column++ {
				fmt.Fprintf(&out, "0x%016x,", values[row*columns+column])
			}
			if columns > 1 {
				out.WriteString("},")
			}
			out.WriteByte('\n')
		}
		out.WriteString("}\n\n")
	}
	return format.Source([]byte(out.String()))
}

func parseTable(text, name string, decimal bool) ([]uint64, error) {
	text = regexp.MustCompile(`(?s)/\*.*?\*/`).ReplaceAllString(text, "")
	if start := strings.Index(text, "#ifdef BIG_ENDI"); start >= 0 {
		if !strings.Contains(text[start:], "#else") {
			return nil, fmt.Errorf("missing big-endian table terminator")
		}
	}
	match := regexp.MustCompile(`\b` + regexp.QuoteMeta(name) + `\b`).FindStringIndex(text)
	if match == nil {
		return nil, fmt.Errorf("missing table %s", name)
	}
	text = text[match[1]:]
	equals := strings.IndexByte(text, '=')
	if equals < 0 {
		return nil, fmt.Errorf("missing table initializer")
	}
	text = text[equals+1:]
	end := strings.IndexByte(text, ';')
	if end < 0 {
		return nil, fmt.Errorf("missing table terminator")
	}
	text = text[:end]
	if decimal {
		numbers := regexp.MustCompile(`[-+]?(?:[0-9]+\.?[0-9]*|\.[0-9]+)(?:[eE][-+]?[0-9]+)?`).FindAllString(text, -1)
		values := make([]uint64, len(numbers))
		for index, number := range numbers {
			value, err := strconv.ParseFloat(number, 64)
			if err != nil {
				return nil, err
			}
			values[index] = math.Float64bits(value)
		}
		return values, nil
	}
	numbers := regexp.MustCompile(`0[xX][0-9a-fA-F]+`).FindAllString(text, -1)
	if len(numbers)%2 != 0 {
		return nil, fmt.Errorf("unpaired binary64 words")
	}
	values := make([]uint64, len(numbers)/2)
	for index := range values {
		high, err := strconv.ParseUint(numbers[index*2][2:], 16, 32)
		if err != nil {
			return nil, err
		}
		low, err := strconv.ParseUint(numbers[index*2+1][2:], 16, 32)
		if err != nil {
			return nil, err
		}
		values[index] = high<<32 | low
	}
	return values, nil
}
